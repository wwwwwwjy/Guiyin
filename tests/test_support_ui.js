const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const path=require('node:path'),root=path.join(__dirname,'..');
const source=fs.readFileSync(path.join(root,'app/static/studio.js'),'utf8');
const html=fs.readFileSync(path.join(root,'app/static/studio.html'),'utf8');
const settings=html.split('<section id="page-settings"')[1].split('</section>')[0];
assert(settings.includes('请作者喝一杯咖啡'));assert(!settings.includes('<img'));
assert(settings.lastIndexOf('support-panel')>settings.lastIndexOf('开源项目与致谢'));
let modalTitle='',modalHtml='';
const ctx={modal:(title,body)=>{modalTitle=title;modalHtml=body}};
vm.createContext(ctx);
vm.runInContext(source.slice(source.indexOf('function supportDialog()'),source.indexOf('let commentSelectedDirs=')),ctx);
assert.equal(modalHtml,'');
ctx.supportDialog();assert.equal(modalTitle,'请作者喝一杯咖啡');
assert(modalHtml.includes('<h3>支付宝</h3>'));assert(modalHtml.includes('<h3>微信</h3>'));
assert.deepEqual([...modalHtml.matchAll(/src="([^"]+)"/g)].map(m=>m[1]),['/static/support-alipay-qr.png','/static/support-wechat-qr.png']);
assert.equal((modalHtml.match(/width="280" height="280"/g)||[]).length,2);
assert(!modalHtml.includes('input'));assert(!modalHtml.includes('http'));
assert(!source.includes('support-edit'));assert(!source.includes('support-form'));
ctx.supportDialog();assert.equal((modalHtml.match(/<img /g)||[]).length,2);
console.log('Support UI passed: click-only dialog, fixed owner assets, equal dimensions, no editor or external image.');
